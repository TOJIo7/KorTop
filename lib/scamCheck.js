// Проверка текста объявления на признаки обмана. Работает в браузере: текст никуда не отправляется.
// Ключи — id признаков из data/scams.json. Ищем слова, а не смысл, поэтому результат — подсказка, а не вердикт.
// Признак too-good («зарплата выше других») по словам не определить, его здесь нет.
const WORD_START = "(?<![\\p{L}\\d])";
const NEAR = "[^.!?\\n]{0,40}?"; // рядом, в том же предложении

const FEES = "оформлени\\p{L}*|трудоустройств\\p{L}*|устройств\\p{L}*|место|места|анкет\\p{L}*|документ\\p{L}*|обучени\\p{L}*|форму|спецодежд\\p{L}*|медкнижк\\p{L}*|регистраци\\p{L}*";
const PAPERS = "патент\\p{L}*|регистраци\\p{L}*|сертификат\\p{L}*|медкнижк\\p{L}*|миграционн\\p{L}*";

const RULES = {
  prepay: [
    "предоплат\\p{L}*",
    "(?:вступительн\\p{L}*\\s+)?взнос\\p{L}*",
    "деньг\\p{L}*\\s+вперед",
    // «оплата 5000 за оформление», но не «оплата 5000 за смену» — это зарплата
    `(?:оплат\\p{L}*|плат\\p{L}*|стоимост\\p{L}*|цена)${NEAR}\\sза\\s+(?:${FEES})`,
    `\\d[\\d\\s]*(?:₽|р\\.?|руб\\p{L}*|тыс\\p{L}*\\.?)?\\s+за\\s+(?:${FEES})`,
    `(?:перевед\\p{L}*|переведи|скин\\p{L}*|отправ\\p{L}*)${NEAR}(?:деньг\\p{L}*|\\d+\\s*(?:₽|р\\.?|руб\\p{L}*|тыс\\p{L}*))`,
    "пешаки\\p{L}*",
  ],
  guarantee: [
    "гарантированн\\p{L}*\\s+(?:работ\\p{L}*|трудоустройств\\p{L}*|устройств\\p{L}*|мест\\p{L}*)",
    "гаранти\\p{L}*\\s+(?:работ\\p{L}*|трудоустройств\\p{L}*)",
    "100\\s*%\\s*(?:гаранти\\p{L}*|трудоустройств\\p{L}*)",
    "без\\s+собеседовани\\p{L}*",
    "кори\\s+кафолатнок",
    "кафолат\\p{L}*",
  ],
  passport: [
    // «копию паспорта отдать» — это нормально, поэтому копию не считаем
    `(?<!копи\\p{L}{0,3}\\s)паспорт\\p{L}*${NEAR}(?:остав\\p{L}*|сдат\\p{L}*|сда[её]\\p{L}*|отда\\p{L}*|забер\\p{L}*|заберем|хранени\\p{L}*|у\\s+нас|переда\\p{L}*)`,
    `(?:остав\\p{L}*|сдат\\p{L}*|отда\\p{L}*|забер\\p{L}*|заберем|переда\\p{L}*)${NEAR}(?<!копи\\p{L}{0,3}\\s)паспорт\\p{L}*`,
    `шиноснома\\p{L}*${NEAR}(?:дих\\p{L}*|гузор\\p{L}*|нигох\\p{L}*)`,
  ],
  "no-contract": [
    "без\\s+(?:трудового\\s+)?(?:договор\\p{L}*|контракт\\p{L}*|оформлени\\p{L}*)",
    "без\\s+(?:патент\\p{L}*|документ\\p{L}*)",
    "неофициальн\\p{L}*",
    "по[-\\s]черному",
    "бе\\s+(?:шартнома|патент|хуччат\\p{L}*)",
  ],
  "fake-documents": [
    `(?:сделаем|сделаю|сделать|делаем|продам|продаю|продаем|купи\\p{L}*)${NEAR}(?:${PAPERS})`,
    "без\\s+(?:экзамен\\p{L}*|очеред\\p{L}*)",
    `(?:${PAPERS})${NEAR}за\\s+\\d+\\s*(?:дн\\p{L}*|день|час\\p{L}*)`,
    "бе\\s+(?:имтихон|навбат)",
  ],
  pressure: [
    // «срочно требуются» пишут и честные работодатели
    "срочно(?!\\s+(?:требу\\p{L}*|нуж\\p{L}*|ищем))",
    "прямо\\s+сейчас",
    "только\\s+сегодня",
    "места\\s+ограничены",
    "последни\\p{L}*\\s+мест\\p{L}*",
    "осталось\\s+\\d+\\s+мест\\p{L}*",
    "успе\\p{L}*",
    "не\\s+упусти\\p{L}*",
    "хозир\\s+карор",
  ],
};

const MATCHERS = Object.entries(RULES).map(([id, patterns]) => ({
  id,
  regex: new RegExp(patterns.map((p) => `${WORD_START}(?:${p})`).join("|"), "giu"),
}));

// Признаки компании: без них стоит уточнить, кто работодатель. Это совет, а не признак обмана
const COMPANY = new RegExp(`${WORD_START}(?:ооо|ип|ао|пао|зао|инн|огрн|компани\\p{L}*|организаци\\p{L}*|предприяти\\p{L}*|завод\\p{L}*|чамъият\\p{L}*|ширкат\\p{L}*)(?![\\p{L}\\d])`, "iu");

// В поиске ё = е, а ҷ, ҳ, ӣ, ӯ, қ, ғ = обычные буквы: так проще и русский, и таджикский текст.
// Замена один к одному, поэтому позиции совпадений подходят и к исходному тексту
const LETTERS = { ё: "е", Ё: "Е", ҷ: "ч", Ҷ: "Ч", ҳ: "х", Ҳ: "Х", ӣ: "и", Ӣ: "И", ӯ: "у", Ӯ: "У", қ: "к", Қ: "К", ғ: "г", Ғ: "Г" };
const normalize = (text) => text.replace(/[ёЁҷҶҳҲӣӢӯӮқҚғҒ]/g, (letter) => LETTERS[letter]);

/**
 * { signs: [id признака], parts: [{ text, signId }], unknownCompany }
 * parts — весь текст по кускам: у подозрительных кусков есть signId, их подсвечиваем.
 */
export function checkAd(text) {
  const search = normalize(text);
  const found = MATCHERS.flatMap(({ id, regex }) =>
    [...search.matchAll(regex)].map((m) => ({ id, start: m.index, end: m.index + m[0].length })),
  ).sort((a, b) => a.start - b.start || b.end - a.end);

  const parts = [];
  let position = 0;
  for (const match of found) {
    if (match.end <= position) continue; // кусок уже подсвечен другим правилом
    const start = Math.max(match.start, position);
    if (start > position) parts.push({ text: text.slice(position, start), signId: null });
    parts.push({ text: text.slice(start, match.end), signId: match.id });
    position = match.end;
  }
  if (position < text.length) parts.push({ text: text.slice(position), signId: null });

  return {
    signs: Object.keys(RULES).filter((id) => found.some((match) => match.id === id)),
    parts,
    unknownCompany: !COMPANY.test(search),
  };
}
